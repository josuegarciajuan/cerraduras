<?php
declare(strict_types=1);

/**
 * bin/seed.php
 *
 * Dev seeding script. Creates (idempotently):
 *   - Baseline api_clients with freshly generated keys.
 *   - One room_type, two rooms and a full-day RENTABLE time_slot for dev.
 *
 * The plaintext keys are written to seeds/dev_api_keys.txt so local tests
 * can use them with curl. That file is git-ignored (.env.example + .env).
 *
 * Running twice is safe: existing rows are kept, no duplicates are created.
 *
 * Usage:
 *   php bin/seed.php
 */

require __DIR__ . '/../src/Support/Autoload.php';

use App\Support\Config;
use App\Infrastructure\Db\PdoFactory;

Config::load(__DIR__ . '/../.env');

$pdo = PdoFactory::make();

echo "[seed] Seeding api_clients ...\n";

// (code, kind, scopes, ip_whitelist)
$clients = [
    ['VB6-MAIN',     'VB6',         'qr:issue,qr:revoke,rooms:read,rooms:state,time-slots:read,stays:read,stays:write,debts:read,presence:read', null],
    ['RPI-DEV',      'RPI',         'qr:validate', null],
    ['FACTORY-DEVICE','RPI',        'factory:announce', null],
    ['ADMIN-CLI',    'ADMIN',       'audit:read,factory:claim,rooms:read,rooms:write,rooms:state,time-slots:read,time-slots:write,locks:open,locks:lock,locks:override,stays:read,stays:write,qr:revoke,debts:read,debts:sync,presence:read,presence:write,switches:write,sim:*', null],
    ['TUYA-BRIDGE',  'TUYA_BRIDGE', 'presence:write', null],
    ['SIM-CLIENT',   'SIM',         'sim:*,presence:write', null],
    // NOTE: this is the API -> WS-VB6 outgoing credential (used by the outbox
    // worker). It is stored here for visibility; the WS-VB6 side validates it
    // against its own WS_API_KEY_HASH.
    ['VB6-BRIDGE',   'VB6_BRIDGE',  'vb6-bridge:read,vb6-bridge:write', null],
];

$keyOut = [];
$selectStmt = $pdo->prepare('SELECT id FROM api_clients WHERE code = :code');
$insertStmt = $pdo->prepare(
    'INSERT INTO api_clients (code, kind, api_key_hash, scopes_csv, ip_whitelist_csv, active)
     VALUES (:code, :kind, :hash, :scopes, :wl, 1)'
);

foreach ($clients as $c) {
    [$code, $kind, $scopes, $wl] = $c;
    $selectStmt->execute([':code' => $code]);
    $existing = $selectStmt->fetch(PDO::FETCH_ASSOC);
    if ($existing !== false) {
        echo "  KEEP {$code} (id={$existing['id']}, key unchanged)\n";
        $keyOut[] = "{$code}\tEXISTING\t(hash already stored; plaintext not recoverable)";
        continue;
    }

    // Generate 48 bytes of random, encode hex (96 chars) as the plaintext key.
    $plaintext = bin2hex(random_bytes(24));
    $hash = hash('sha256', $plaintext);
    $insertStmt->execute([
        ':code'   => $code,
        ':kind'   => $kind,
        ':hash'   => $hash,
        ':scopes' => $scopes,
        ':wl'     => $wl,
    ]);
    $id = $pdo->lastInsertId();
    echo "  NEW  {$code} (id={$id})\n";
    $keyOut[] = "{$code}\t{$plaintext}";
}

// --- Minimal dev fixtures (TSK-035) ---
echo "[seed] Seeding dev room_type + rooms + time_slots ...\n";

$pdo->exec("INSERT IGNORE INTO room_types
    (code, name, grace_minutes, exit_presence_gap_seconds, reentry_cooldown_seconds, qr_usage_window_minutes)
    VALUES ('STANDARD', 'Habitación estándar', 5, 15, 20, 30)");

$rtId = (int) $pdo->query("SELECT id FROM room_types WHERE code='STANDARD'")->fetchColumn();

$pdo->prepare("INSERT IGNORE INTO rooms (code, room_type_id, status) VALUES (:c, :rt, 'FREE')")
    ->execute([':c' => '101', ':rt' => $rtId]);
$pdo->prepare("INSERT IGNORE INTO rooms (code, room_type_id, status) VALUES (:c, :rt, 'FREE')")
    ->execute([':c' => '102', ':rt' => $rtId]);

// Only seed time_slots for STANDARD if none exist
$count = (int) $pdo->prepare("SELECT COUNT(*) FROM time_slots WHERE room_type_id = :rt")
    ->execute([':rt' => $rtId]);
$hasSlots = (int) $pdo->query("SELECT COUNT(*) FROM time_slots WHERE room_type_id={$rtId}")->fetchColumn();
if ($hasSlots === 0) {
    $pdo->prepare("INSERT INTO time_slots (room_type_id, starts_at, ends_at, kind) VALUES (:rt, '00:00:00', '23:59:59', 'RENTABLE')")
        ->execute([':rt' => $rtId]);
    echo "  NEW  time_slots STANDARD 00:00-24:00 RENTABLE\n";
} else {
    echo "  KEEP time_slots already defined ({$hasSlots})\n";
}

// --- Write plaintext key file ---
$file = __DIR__ . '/../seeds/dev_api_keys.txt';
@mkdir(dirname($file), 0775, true);
$header  = "# Dev API keys generated by bin/seed.php\n";
$header .= "# This file is git-ignored. Copy values into your HTTP client.\n";
$header .= "# code\tplaintext_key\n";
file_put_contents($file, $header . implode("\n", $keyOut) . "\n");
echo "[seed] Plaintext keys (for NEW rows only) written to: {$file}\n";

// --- Seed system_settings from .env ---
echo "[seed] Seeding system_settings ...\n";

$settingsSeed = [
    ['api', 'operation', 'SIMULATED_MODE',    Config::get('SIMULATED_MODE', 'true'),                                        'Modo simulación (true/false)',                                         0],
    ['api', 'operation', 'LOCK_PROVIDER',     Config::get('LOCK_PROVIDER', 'LOCAL'),                                       'Proveedor de cerradura: LOCAL|ESP32|TUYA|SIMULATED',                   0],
    ['api', 'operation', 'QR_EXP_FROM_DB',    Config::get('QR_EXP_FROM_DB', 'false'),                                     'Caducidad QR desde BD (true=dev)',                                     0],
    ['api', 'connections', 'TUYA_ACCESS_ID',  Config::get('TUYA_ACCESS_ID', ''),                                          'Tuya Cloud Access ID',                                                 1],
    ['api', 'connections', 'TUYA_ACCESS_SECRET', Config::get('TUYA_ACCESS_SECRET', ''),                                   'Tuya Cloud Access Secret',                                             1],
    ['api', 'connections', 'TUYA_BASE_URL',   Config::get('TUYA_BASE_URL', 'https://openapi.tuyaeu.com'),                 'Tuya Cloud Base URL',                                                  0],
    ['api', 'connections', 'WSVB6_BASE_URL',  Config::get('WSVB6_BASE_URL', 'http://127.0.0.1:8081/ws-vb6/v1'),           'URL del bridge WS-VB6',                                                0],
    ['api', 'connections', 'WSVB6_API_KEY',   Config::get('WSVB6_API_KEY', ''),                                           'API Key del bridge WS-VB6',                                            1],
    ['api', 'logging',    'LOG_LEVEL',        Config::get('LOG_LEVEL', 'debug'),                                          'Nivel de log: debug|info|warning|error',                               0],
    ['api', 'logging',    'LOG_PATH',         Config::get('LOG_PATH', 'logs/api.log'),                                    'Ruta del archivo de log',                                              0],
    ['api', 'anomaly',    'anomaly.enabled_types', json_encode(['A1','A2','A3','A4','A5','A6','A7','A8']),          'Tipos de anomalía habilitados (JSON array)',                            0],
];

$settingsInsert = $pdo->prepare(
    'INSERT IGNORE INTO system_settings (service, category, setting_key, value, description, is_sensitive, created_at, updated_at)
     VALUES (:svc, :cat, :key, :val, :desc, :sens, UTC_TIMESTAMP(3), UTC_TIMESTAMP(3))'
);

foreach ($settingsSeed as $s) {
    [$svc, $cat, $key, $val, $desc, $sens] = $s;
    $settingsInsert->execute([
        ':svc'  => $svc,
        ':cat'  => $cat,
        ':key'  => $key,
        ':val'  => $val,
        ':desc' => $desc,
        ':sens' => $sens,
    ]);
    echo "  SEED {$key}\n";
}

echo "[seed] Done.\n";
