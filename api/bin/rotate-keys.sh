#!/usr/bin/env bash
# =============================================================================
# rotate-keys.sh — Regenera claves API y sincroniza todos los archivos
#
# Uso: bash bin/rotate-keys.sh
#
#Qué hace:
#  1. Genera nuevas claves para los 6 clientes en dev_api_keys.txt
#  2. Actualiza api_clients en la BD con los nuevos hashes SHA-256
#  3. Genera VB6-BRIDGE y sincroniza:
#       - api/.env  → WSVB6_API_KEY (plaintext)
#       - ws-vb6/.env → WS_API_KEY_HASH (hash SHA-256)
#       - api/seeds/dev_api_keys.txt → VB6-BRIDGE plaintext (para tests)
#
# IMPORTANTE: ejecutar con PHP y MySQL corriendo.
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

cd "$PROJECT_DIR"

# --- Colores ---
G='\033[0;32m'
R='\033[0;31m'
Y='\033[1;33m'
NC='\033[0m'

echo ""
echo "=== Rotate Keys ==="

# =============================================================================
# 1. Generar nuevas claves
# =============================================================================
echo "Generando claves..."

VB6_MAIN_KEY=$(openssl rand -hex 24)
RPI_DEV_KEY=$(openssl rand -hex 24)
ADMIN_CLI_KEY=$(openssl rand -hex 24)
TUYA_BRIDGE_KEY=$(openssl rand -hex 24)
SIM_CLIENT_KEY=$(openssl rand -hex 24)
VB6_BRIDGE_KEY=$(openssl rand -hex 24)

echo "  VB6-MAIN:    ${VB6_MAIN_KEY:0:16}..."
echo "  RPI-DEV:     ${RPI_DEV_KEY:0:16}..."
echo "  ADMIN-CLI:   ${ADMIN_CLI_KEY:0:16}..."
echo "  TUYA-BRIDGE: ${TUYA_BRIDGE_KEY:0:16}..."
echo "  SIM-CLIENT:  ${SIM_CLIENT_KEY:0:16}..."
echo "  VB6-BRIDGE:  ${VB6_BRIDGE_KEY:0:16}..."

# =============================================================================
# 2. Calcular hashes SHA-256
# =============================================================================
H_VB6_MAIN=$(echo -n "$VB6_MAIN_KEY" | sha256sum | awk '{print $1}')
H_RPI_DEV=$(echo -n "$RPI_DEV_KEY" | sha256sum | awk '{print $1}')
H_ADMIN_CLI=$(echo -n "$ADMIN_CLI_KEY" | sha256sum | awk '{print $1}')
H_TUYA_BRIDGE=$(echo -n "$TUYA_BRIDGE_KEY" | sha256sum | awk '{print $1}')
H_SIM_CLIENT=$(echo -n "$SIM_CLIENT_KEY" | sha256sum | awk '{print $1}')
H_VB6_BRIDGE=$(echo -n "$VB6_BRIDGE_KEY" | sha256sum | awk '{print $1}')

# =============================================================================
# 3. Actualizar api_clients en la BD
echo ""
echo "Actualizando api_clients en BD..."

# Leer credenciales de api/.env
DB_HOST=$(grep "^DB_HOST" "$PROJECT_DIR/api/.env" | cut -d= -f2 | tr -d ' ')
DB_PORT=$(grep "^DB_PORT" "$PROJECT_DIR/api/.env" | cut -d= -f2 | tr -d ' ')
DB_NAME=$(grep "^DB_NAME" "$PROJECT_DIR/api/.env" | cut -d= -f2 | tr -d ' ')
DB_USER=$(grep "^DB_USER" "$PROJECT_DIR/api/.env" | cut -d= -f2 | tr -d ' ')
DB_PASS=$(grep "^DB_PASS" "$PROJECT_DIR/api/.env" | cut -d= -f2 | tr -d ' ')

# Intentar múltiples métodos de conexión MySQL
run_mysql() {
    local sql="$1"
    local result
    # 1) TCP explícito
    result=$(mysql -u"$DB_USER" -p"$DB_PASS" -h"$DB_HOST" -P"$DB_PORT" "$DB_NAME" -e "$sql" 2>&1)
    [ $? -eq 0 ] && echo "$result" && return 0
    # 2) Socket local (sin -h)
    result=$(mysql -u"$DB_USER" -p"$DB_PASS" "$DB_NAME" -e "$sql" 2>&1)
    [ $? -eq 0 ] && echo "$result" && return 0
    # 3) Root sin contraseña
    result=$(mysql -u root "$DB_NAME" -e "$sql" 2>&1)
    [ $? -eq 0 ] && echo "$result" && return 0
    echo "[WARN] MySQL connection failed for all methods"
    echo "$result"
    return 1
}

update_client() {
    local code="$1"
    local hash="$2"
    local sql="UPDATE api_clients SET api_key_hash='$hash' WHERE code='$code';"
    if run_mysql "$sql" > /dev/null 2>&1; then
        echo "  ✓ $code updated"
    else
        echo "  [WARN] Could not update $code (MySQL may be unavailable)"
    fi
}

update_client "VB6-MAIN"     "$H_VB6_MAIN"
update_client "RPI-DEV"      "$H_RPI_DEV"
update_client "ADMIN-CLI"    "$H_ADMIN_CLI"
update_client "TUYA-BRIDGE"  "$H_TUYA_BRIDGE"
update_client "SIM-CLIENT"   "$H_SIM_CLIENT"
update_client "VB6-BRIDGE"   "$H_VB6_BRIDGE"

# =============================================================================
# 4. Escribir dev_api_keys.txt
# =============================================================================
cat > "$PROJECT_DIR/api/seeds/dev_api_keys.txt" <<EOF
# Dev API keys — generated by rotate-keys.sh $(date '+%Y-%m-%d %H:%M:%S')
# code	plaintext_key
VB6-MAIN	$VB6_MAIN_KEY
RPI-DEV	$RPI_DEV_KEY
ADMIN-CLI	$ADMIN_CLI_KEY
TUYA-BRIDGE	$TUYA_BRIDGE_KEY
SIM-CLIENT	$SIM_CLIENT_KEY
VB6-BRIDGE	$VB6_BRIDGE_KEY
EOF

echo "  Claves escritas en api/seeds/dev_api_keys.txt"

# =============================================================================
# 5. Actualizar WSVB6_API_KEY en api/.env
# =============================================================================
sed -i "s|^WSVB6_API_KEY=.*|WSVB6_API_KEY=$VB6_BRIDGE_KEY|" "$PROJECT_DIR/api/.env"
echo "  WSVB6_API_KEY actualizada en api/.env"

# =============================================================================
# 6. Actualizar WS_API_KEY_HASH en ws-vb6/.env
# =============================================================================
sed -i "s|^WS_API_KEY_HASH=.*|WS_API_KEY_HASH=$H_VB6_BRIDGE|" "$PROJECT_DIR/ws-vb6/.env"
echo "  WS_API_KEY_HASH actualizada en ws-vb6/.env"

# =============================================================================
# 7. Verificar sincronización
# =============================================================================
echo ""
echo "=== Verificación ==="

KEY_IN_API=$(grep '^WSVB6_API_KEY' "$PROJECT_DIR/api/.env" | cut -d= -f2- | tr -d ' ')
HASH_IN_WS=$(grep '^WS_API_KEY_HASH' "$PROJECT_DIR/ws-vb6/.env" | cut -d= -f2- | tr -d ' ')
CALC_HASH=$(echo -n "$KEY_IN_API" | sha256sum | awk '{print $1}')
VB6_BRIDGE_IN_SEEDS=$(grep '^VB6-BRIDGE' "$PROJECT_DIR/api/seeds/dev_api_keys.txt" | awk '{print $2}')

echo "  api/.env          WSVB6_API_KEY  = ${KEY_IN_API:0:16}..."
echo "  ws-vb6/.env       WS_API_KEY_HASH = $HASH_IN_WS"
echo "  Calculated SHA256 of WSVB6_API_KEY = $CALC_HASH"
echo "  dev_api_keys.txt  VB6-BRIDGE     = ${VB6_BRIDGE_IN_SEEDS:0:16}..."

if [ "$HASH_IN_WS" = "$CALC_HASH" ]; then
    echo -e "  ${G}✓ Hash SYNCED${NC}"
else
    echo -e "  ${R}✗ Hash MISMATCH!${NC}"
    echo "  Expected: $CALC_HASH"
    echo "  Got:      $HASH_IN_WS"
fi

# =============================================================================
# 8. Reiniciar servidores
# =============================================================================
echo ""
echo "=== Reiniciando servidores ==="

# API server
pkill -f "php -S 127.0.0.1:8080" 2>/dev/null || true
sleep 1
cd "$PROJECT_DIR/api"
php -S 127.0.0.1:8080 -t public public/index.php >> logs/php-server.log 2>&1 &
echo "  API server (8080) started"

# WS-VB6 server
pkill -f "php -S 127.0.0.1:8081" 2>/dev/null || true
sleep 1
cd "$PROJECT_DIR/ws-vb6"
php -S 127.0.0.1:8081 -t public public/index.php >> logs/php-server.log 2>&1 &
echo "  WS-VB6 server (8081) started"

sleep 2

# =============================================================================
# 9. Test rápido
# =============================================================================
echo ""
echo "=== Tests de verificación ==="

# Test API health
HTTP=$(curl -s -o /dev/null -w "%{http_code}" http://127.0.0.1:8080/api/v1/health)
if [ "$HTTP" = "200" ]; then
    echo -e "  ${G}✓${NC} API health: HTTP $HTTP"
else
    echo -e "  ${R}✗${NC} API health: HTTP $HTTP (esperado 200)"
fi

# Test WS health
WS_HTTP=$(curl -s -o /dev/null -w "%{http_code}" http://127.0.0.1:8081/ws-vb6/v1/health)
if [ "$WS_HTTP" = "200" ]; then
    echo -e "  ${G}✓${NC} WS-VB6 health: HTTP $WS_HTTP"
else
    echo -e "  ${R}✗${NC} WS-VB6 health: HTTP $WS_HTTP (esperado 200)"
fi

# Test WS with VB6-BRIDGE key
VB6_KEY=$(grep '^VB6-BRIDGE' "$PROJECT_DIR/api/seeds/dev_api_keys.txt" | awk '{print $2}')
WS_AUTH=$(curl -s -o /dev/null -w "%{http_code}" \
    -H "X-API-Key: $VB6_KEY" \
    http://127.0.0.1:8081/ws-vb6/v1/health)
if [ "$WS_AUTH" = "200" ]; then
    echo -e "  ${G}✓${NC} WS-VB6 auth con VB6-BRIDGE key: HTTP $WS_AUTH"
else
    echo -e "  ${R}✗${NC} WS-VB6 auth con VB6-BRIDGE key: HTTP $WS_AUTH (esperado 200)"
fi

# Test API con ADMIN-CLI key
ADM_KEY=$(grep '^ADMIN-CLI' "$PROJECT_DIR/api/seeds/dev_api_keys.txt" | awk '{print $2}')
API_AUTH=$(curl -s -o /dev/null -w "%{http_code}" \
    -H "X-API-Key: $ADM_KEY" \
    http://127.0.0.1:8080/api/v1/rooms)
if [ "$API_AUTH" = "200" ]; then
    echo -e "  ${G}✓${NC} API auth con ADMIN-CLI: HTTP $API_AUTH"
else
    echo -e "  ${R}✗${NC} API auth con ADMIN-CLI: HTTP $API_AUTH (esperado 200)"
fi

echo ""
echo "=== Listo — Ejecuta 'bash bin/run-tests.sh' para verificar todo ==="
echo ""