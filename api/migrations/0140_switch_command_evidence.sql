-- F112/RF-261..RF-263: evidencia persistente de ordenes a interruptores Zigbee.
-- Tabla aditiva. No sustituye device_commands (cola de los ESP).
CREATE TABLE IF NOT EXISTS `switch_command_evidence` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `operation_id` CHAR(36) NOT NULL,
  `room_id` BIGINT UNSIGNED NOT NULL,
  `device_id` BIGINT UNSIGNED NOT NULL,
  `external_id` VARCHAR(128) NOT NULL,
  `provider` VARCHAR(32) NOT NULL DEFAULT 'ZIGBEE2MQTT',
  `origin` VARCHAR(32) NOT NULL DEFAULT 'manual',
  `action` VARCHAR(8) NOT NULL,
  `actor` VARCHAR(64) NULL,
  `requested_at` DATETIME(3) NOT NULL,
  `publish_ok` TINYINT(1) NULL,
  `publish_error` VARCHAR(255) NULL,
  `published_at` DATETIME(3) NULL,
  `prior_state` VARCHAR(8) NULL,
  `prior_state_at` DATETIME(3) NULL,
  `reported_state` VARCHAR(8) NULL,
  `reported_at` DATETIME(3) NULL,
  `fresh` TINYINT(1) NULL,
  `report_source` VARCHAR(16) NULL,
  `human_state` VARCHAR(8) NULL,
  `human_at` DATETIME(3) NULL,
  `verdict` VARCHAR(24) NOT NULL DEFAULT 'indeterminate',
  `diagnosis` VARCHAR(64) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_switch_evidence_operation` (`operation_id`),
  KEY `idx_switch_evidence_room_time` (`room_id`, `requested_at`),
  KEY `idx_switch_evidence_device_time` (`device_id`, `requested_at`),
  KEY `idx_switch_evidence_verdict` (`verdict`, `requested_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
